package soa.userservice.service;

import java.util.List;
import java.util.Optional;

import org.springframework.security.access.AccessDeniedException;
import org.springframework.security.core.Authentication;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.stereotype.Service;

import soa.userservice.dto.UserRequest;
import soa.userservice.dto.UserResponse;
import soa.userservice.dto.UserUpdateRequest;
import soa.userservice.exception.UserNotFoundException;
import soa.userservice.model.User;
import soa.userservice.repository.UserRepository;

@Service
public class UserService {

    private final UserRepository userRepository;

    public UserService(UserRepository userRepository) {
        this.userRepository = userRepository;
    }

    // CREATE - Persists user using database-generated primary key (id)
    public UserResponse createUser(UserRequest request) {

        if (request == null) {
            throw new IllegalArgumentException("User request cannot be null");
        }

        if (request.getRole() == null || request.getRole().isBlank()) {
            throw new IllegalArgumentException("role is required (STUDENT or INSTRUCTOR)");
        }

        String role = request.getRole().trim().toUpperCase();
        if (!role.equals("STUDENT") && !role.equals("INSTRUCTOR") && !role.equals("ADMIN")) {
            throw new IllegalArgumentException("role must be STUDENT, INSTRUCTOR, or ADMIN");
        }

        // Duplicate email validation
        String normalizedEmail = null;
        if (request.getEmail() != null && !request.getEmail().isBlank()) {
            normalizedEmail = request.getEmail().trim().toLowerCase();
            if (userRepository.existsByEmailIgnoreCase(normalizedEmail)) {
                throw new IllegalStateException("User with email '" + request.getEmail().trim() + "' already exists");
            }
        }

        User user = new User();
        // Client-provided primary key is not accepted; id is generated by PostgreSQL identity
        user.setName(request.getName());
        user.setEmail(normalizedEmail);
        user.setPhone(request.getPhone());
        user.setRole(role);
        user.setDepartment(request.getDepartment());

        if ("STUDENT".equalsIgnoreCase(role)) {
            user.setStudentId(request.getStudentId());
            user.setInstructorId(null);
        } else if ("INSTRUCTOR".equalsIgnoreCase(role)) {
            user.setInstructorId(request.getInstructorId());
            user.setStudentId(null);
        } else {
            user.setStudentId(request.getStudentId());
            user.setInstructorId(request.getInstructorId());
        }

        // Save with database-generated identity
        User savedUser = userRepository.save(user);

        // Ensure user_id column reflects the auto-generated unique ID for query consistency
        if (savedUser.getUserId() == null || savedUser.getUserId().isBlank()) {
            savedUser.setUserId(String.valueOf(savedUser.getId()));
            savedUser = userRepository.save(savedUser);
        }

        return convertToResponse(savedUser);
    }

    // READ ALL (Admin only via SecurityConfig)
    public List<UserResponse> getAllUsers() {
        return userRepository.findAll().stream()
                .map(this::convertToResponse)
                .toList();
    }

    // READ BY id / identifier
    public UserResponse getUserById(String identifier) {
        checkUserOwnership(identifier);
        User user = findUserByIdentifier(identifier)
                .orElseThrow(() -> new UserNotFoundException("User not found with id: " + identifier));
        return convertToResponse(user);
    }

    // CHECK EXISTS (used by other services via Feign)
    public boolean existsById(String identifier) {
        return findUserByIdentifier(identifier).isPresent();
    }

    // UPDATE
    public UserResponse updateUser(String identifier, UserUpdateRequest request) {
        checkUserOwnership(identifier);
        User user = findUserByIdentifier(identifier)
                .orElseThrow(() -> new UserNotFoundException("User not found with id: " + identifier));

        user.setName(request.getName());
        user.setPhone(request.getPhone());
        user.setDepartment(request.getDepartment());

        if (request.getStudentId() != null && !request.getStudentId().isBlank()) {
            user.setStudentId(request.getStudentId());
        }
        if (request.getInstructorId() != null && !request.getInstructorId().isBlank()) {
            user.setInstructorId(request.getInstructorId());
        }

        return convertToResponse(userRepository.save(user));
    }

    // DELETE
    public void deleteUser(String identifier) {
        checkUserOwnership(identifier);
        User user = findUserByIdentifier(identifier)
                .orElseThrow(() -> new UserNotFoundException("User not found with id: " + identifier));
        userRepository.delete(user);
    }

    public Optional<User> findUserByIdentifier(String identifier) {
        if (identifier == null || identifier.isBlank()) {
            return Optional.empty();
        }

        String trimmed = identifier.trim();

        // 1. Try parsing as numeric primary key id
        try {
            Long numericId = Long.parseLong(trimmed);
            Optional<User> byId = userRepository.findById(numericId);
            if (byId.isPresent()) {
                return byId;
            }
        } catch (NumberFormatException ignored) {
        }

        // 2. Try looking up by userId column
        Optional<User> byUserId = userRepository.findByUserId(trimmed);
        if (byUserId.isPresent()) {
            return byUserId;
        }

        // 3. Try looking up by studentId
        Optional<User> byStudent = userRepository.findByStudentId(trimmed);
        if (byStudent.isPresent()) {
            return byStudent;
        }

        // 4. Try looking up by instructorId
        Optional<User> byInstructor = userRepository.findByInstructorId(trimmed);
        if (byInstructor.isPresent()) {
            return byInstructor;
        }

        // 5. Try looking up by email
        Optional<User> byEmail = userRepository.findByEmailIgnoreCase(trimmed);
        if (byEmail.isPresent()) {
            return byEmail;
        }

        // 6. Try looking up by name
        return userRepository.findByNameIgnoreCase(trimmed);
    }

    private void checkUserOwnership(String identifier) {
        Authentication auth = SecurityContextHolder.getContext().getAuthentication();
        if (auth != null && auth.isAuthenticated() && !"anonymousUser".equals(auth.getPrincipal())) {
            boolean isAdmin = auth.getAuthorities().stream().anyMatch(a -> a.getAuthority().equals("ROLE_ADMIN"));
            if (!isAdmin) {
                String currentUser = auth.getName();
                if (currentUser != null) {
                    if (currentUser.equalsIgnoreCase(identifier)) {
                        return;
                    }
                    Optional<User> targetUser = findUserByIdentifier(identifier);
                    if (targetUser.isPresent()) {
                        User u = targetUser.get();
                        if (currentUser.equalsIgnoreCase(String.valueOf(u.getId()))
                                || (u.getUserId() != null && currentUser.equalsIgnoreCase(u.getUserId()))
                                || (u.getStudentId() != null && currentUser.equalsIgnoreCase(u.getStudentId()))
                                || (u.getInstructorId() != null && currentUser.equalsIgnoreCase(u.getInstructorId()))
                                || (u.getEmail() != null && (currentUser.equalsIgnoreCase(u.getEmail()) || u.getEmail().toLowerCase().startsWith(currentUser.toLowerCase() + "@")))
                                || (u.getName() != null && (currentUser.equalsIgnoreCase(u.getName())
                                        || u.getName().replace(" ", ".").equalsIgnoreCase(currentUser)
                                        || u.getName().replace(".", " ").equalsIgnoreCase(currentUser)))) {
                            return;
                        }

                        if (auth.getDetails() instanceof io.jsonwebtoken.Claims claims) {
                            String claimUserId = claims.get("userId", String.class);
                            String claimEmail = claims.get("email", String.class);
                            if (claimUserId != null && (claimUserId.equalsIgnoreCase(String.valueOf(u.getId())) || claimUserId.equalsIgnoreCase(u.getUserId()))) {
                                return;
                            }
                            if (claimEmail != null && u.getEmail() != null && claimEmail.equalsIgnoreCase(u.getEmail())) {
                                return;
                            }
                        }
                    }
                    throw new AccessDeniedException("Users can only access their own profile");
                }
            }
        }
    }

    private UserResponse convertToResponse(User user) {
        UserResponse response = new UserResponse();
        response.setId(user.getId());
        response.setUserId(user.getUserId() != null ? user.getUserId() : String.valueOf(user.getId()));
        response.setName(user.getName());
        response.setEmail(user.getEmail());
        response.setPhone(user.getPhone());
        response.setRole(user.getRole());
        response.setDepartment(user.getDepartment());
        response.setStudentId(user.getStudentId());
        response.setInstructorId(user.getInstructorId());
        return response;
    }
}