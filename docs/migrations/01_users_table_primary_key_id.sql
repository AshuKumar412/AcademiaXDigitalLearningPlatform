-- Purpose: Fix duplicate user ID issue by establishing a database-generated
--          identity primary key on users.id while preserving existing data.
-- =========================================================================

-- 1. Add id column with auto-generating identity if not exists
ALTER TABLE users ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY;

-- 2. Drop legacy primary key constraint on user_id
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_pkey;

-- 3. Add primary key constraint on newly created id column
ALTER TABLE users ADD CONSTRAINT users_pkey PRIMARY KEY (id);

-- 4. Allow user_id to be nullable (populated automatically or preserved)
ALTER TABLE users ALTER COLUMN user_id DROP NOT NULL;

-- 5. Synchronize the identity sequence with existing records
SELECT setval(pg_get_serial_sequence('users', 'id'), coalesce(max(id), 1), max(id) IS NOT NULL) FROM users;

-- 6. Enforce email uniqueness constraint at database level
CREATE UNIQUE INDEX IF NOT EXISTS uk_users_email_lower ON users (lower(trim(email))) WHERE email IS NOT NULL;
